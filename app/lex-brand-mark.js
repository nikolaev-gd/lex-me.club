// lex-brand-mark.js — знак Lex, общий для всех поверхностей.
//
// Та же буква, что на значке расширения и в строке меню: контур взят дословно
// из design/lex-icon/lex-icon.svg, откуда сделаны все PNG. Чёрной подложки
// здесь нет намеренно — на значке она нужна, чтобы буква читалась на любом
// фоне панели браузера, а внутри чата фон свой, и квадрат читался бы как
// лишний прямоугольник (ровно так он и выглядел на панели поверх YouTube).
//
// Вектором, а не картинкой: чат рисуется ВНУТРИ чужой страницы, и ссылка вида
// chrome-extension://… работала бы только через web_accessible_resources, то
// есть открывала бы файл любому сайту; а собранная страница lex-me.club/app —
// плоский каталог без какого-либо конвейера картинок (build-webchat.mjs
// собирает только теги <script>/<link>). Разметка описана один раз здесь и
// читается обоими.
//
// Расширение грузит файл через manifest content_scripts (и STANDALONE_CHAT_DEPS
// в background.js); страница — тегом <script src="../lex-brand-mark.js">.
// Отдаёт global.LexBrandMark.
(function (global) {
  'use strict';

  const COLOR = '#F2C14B';
  const PATH = 'M 236 271 A 97 97 0 0 1 430 271 L 430 656 L 691 656 A 97 97 0 0 1 691 850 L 452 850 C 322.5 850 236 763.5 236 634 Z';

  // ⚠️ Рамка считается по НАСТОЯЩИМ границам контура, а не по координатам его
  // опорных точек. В пути две полуокружности радиусом 97 — круглая макушка
  // (центр 333,271 → верх на y=174) и круглый правый конец (центр 691,753 →
  // край на x=788). Обе выходят за опорные точки, и рамка «236 271 455 579»,
  // снятая с точек, срезала ровно их: буква выходила с плоской макушкой и
  // обрубленным правым концом. Настоящие границы: x 236…788, y 174…850.
  const VIEW_W = 552;   // 788 − 236
  const VIEW_H = 676;   // 850 − 174
  const VIEW_BOX = '236 174 ' + VIEW_W + ' ' + VIEW_H;

  // height — высота САМОЙ БУКВЫ в пикселях; ширина считается из пропорции.
  // 48 по умолчанию: столько буква занимала в квадрате 72×72, которым её
  // рисовала страница картинкой (676/1024 × 72 ≈ 47,5).
  function svgMarkup(height) {
    const h = Number(height) || 48;
    const w = Math.round(h * VIEW_W / VIEW_H);
    return `<svg viewBox="${VIEW_BOX}" width="${w}" height="${h}" role="img" aria-hidden="true" focusable="false"><path fill="${COLOR}" d="${PATH}"/></svg>`;
  }

  global.LexBrandMark = { svgMarkup, COLOR, VIEW_BOX, PATH };
})(typeof self !== 'undefined' ? self : globalThis);
