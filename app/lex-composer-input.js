// lex-composer-input.js — одно правило на четыре места: куда встаёт курсор и
// что делает Enter.
//
// Мест, где человек печатает учителю, четыре: приложение на iPhone, программа
// для Мака, страница lex-me.club/app в браузере и расширение (главный чат и
// видеочат). Кода за ними ДВА — страница и расширение написаны отдельно, — и
// правило легко разъезжается: в одном окне Enter отправляет, в другом переносит
// строку, в одном курсор встаёт сам, в другом нет. Поэтому правило живёт здесь,
// а места только зовут.
//
// Файл ничего не знает про конкретное поле и ни за чем не следит: две функции,
// обе без состояния. Подключён и в `lex-surface-deps.js` (расширение), и в
// `webchat/index.html` (страница, а через неё обе оболочки Apple).
(function (global) {
  'use strict';

  if (global.LexComposerInput) return;

  // ── Где мы ────────────────────────────────────────────────────────────────
  //
  // Оболочка объявляет себя САМА, пометкой `window.__lexShell`, которую ставит
  // родной код до загрузки страницы (`WKUserScript` на documentStart). Угадывать
  // по строке браузера или по наличию мостов нельзя: у Мака и у iPhone внутри
  // один и тот же WebKit и одна и та же страница, а вести себя они должны
  // по-разному — у одного клавиатура на столе, у другого на экране.
  function shellPlatform() {
    try {
      const s = global.__lexShell;
      if (s && typeof s.platform === 'string') return s.platform;
    } catch (_) { /* noop */ }
    return null;
  }

  // Клавиатура ЭКРАННАЯ — то есть её появление отнимает половину экрана и её
  // нельзя поднять без причины.
  //
  // Проверяется указатель, а не ширина: планшет широкий, а клавиатура у него
  // всё равно экранная. В расширении эта ветка не срабатывает никогда — оно
  // живёт только в настольном Chrome.
  function onScreenKeyboard() {
    const p = shellPlatform();
    if (p === 'ios') return true;
    if (p === 'macos') return false;
    try {
      return !!(global.matchMedia && global.matchMedia('(pointer: coarse)').matches);
    } catch (_) { return false; }
  }

  // ── Фокус ─────────────────────────────────────────────────────────────────
  //
  // `raiseKeyboard` — это утверждение вызывающего: «окно сейчас открыл ЧЕЛОВЕК
  // своим нажатием». Только тогда позволено поднимать экранную клавиатуру и
  // только тогда в расширении позволено забирать клавиатуру у чужой страницы:
  // окно, открывшееся само (доставка выбранного слова, вход из попапа,
  // восстановление вкладки), фокус не трогает — иначе буквы человека, который
  // пишет комментарий на YouTube, уедут в чат Lex.
  //
  // Без него функция ведёт себя тише: на столе фокус ставит, на экранной
  // клавиатуре — нет. Это прежнее поведение страницы, и оно остаётся для смены
  // беседы: человек нажал «прочитать», а не «печатать».
  function focus(el, opts) {
    if (!el) return false;
    const raise = !!(opts && opts.raiseKeyboard);
    if (!raise && onScreenKeyboard()) return false;
    try {
      el.focus();
      // Курсор в конец набранного, а не в начало: поле часто уже заполнено
      // (правка хода, доставка выделенного куска), и печатать человек будет
      // дальше, а не перед чужим текстом.
      if (typeof el.setSelectionRange === 'function' && typeof el.value === 'string') {
        const end = el.value.length;
        el.setSelectionRange(end, end);
      }
    } catch (_) { return false; }
    return true;
  }

  // ── Расфокус ──────────────────────────────────────────────────────────────
  //
  // Симметрично `focus`: снять курсор с поля и, на экранной клавиатуре, убрать
  // и её. WebKit сам прячет клавиатуру по настоящему тычку пальцем в другое
  // место — но НЕ по жесту протяжки (`pointermove`), поэтому там, где место
  // открывается или закрывается свайпом (боковая панель бесед), полагаться на
  // это поведение браузера нельзя: расфокус нужно звать явно, в одной точке,
  // одинаковой для кнопки и для жеста.
  function blur(el) {
    if (!el) return false;
    try {
      if (global.document && global.document.activeElement === el) el.blur();
    } catch (_) { return false; }
    return true;
  }

  // ── Каретка встала на самом деле? ─────────────────────────────────────────
  //
  // `focus()` возвращает «получилось» слишком щедро: он говорит только о том,
  // что вызов не бросил исключение. На iPhone замерено (2026-08-21, живой
  // телефон): при запуске приложения тот же вызов записывает поле в
  // `document.activeElement`, а каретки нет и клавиатура не поднимается — окно
  // ещё не может взять клавиатуру себе, потому что приложение не закончило
  // переход в активное состояние. Через две секунды тот же вызов срабатывает
  // полностью. Значит верить надо не вызову, а признакам.
  //
  // Признака два, и они независимы:
  //  1. `document.hasFocus()` — окно действительно держит клавиатуру;
  //  2. видимая область стала заметно ниже окна — экранная клавиатура откусила
  //     свою часть (замер на телефоне: 609 против 956).
  // Второй нужен потому, что первый на разных оболочках приходит с задержкой;
  // порог в 80 px берёт настоящую клавиатуру и не ловит адресную строку.
  function caretIsLive(el) {
    if (!el) return false;
    try {
      if (global.document && global.document.activeElement !== el) return false;
      if (global.document && global.document.hasFocus()) return true;
      const vv = global.visualViewport;
      if (vv && vv.height && global.innerHeight && (global.innerHeight - vv.height) > 80) return true;
    } catch (_) { /* noop */ }
    return false;
  }

  // Сколько держать попытки — и ровно столько же держится заставка оболочки.
  //
  // Решение владельца от 2026-08-21: две секунды и ни секундой больше. Прежние
  // восемь отменены. Число одно на все поверхности страницы; у оболочек есть
  // своя копия срока в родном коде, и она обязана совпадать — снять заставку,
  // когда страница не приехала вовсе, страница не может по определению
  // (`ios/LexChat/LexChat/ChatWebView.swift`, `macos/Sources/LexShell/AppDelegate.swift`).
  const LAUNCH_HOLD_MS = 2000;

  // Ставить курсор, пока он не встанет ПО-НАСТОЯЩЕМУ, но не дольше срока.
  //
  // Зачем повтор, если есть вызов из оболочки по активации: моменты «окно может
  // взять клавиатуру» и «страница готова» приходят в любом порядке и на разных
  // устройствах по-разному. Ждать конкретного из них — значит выбрать порядок и
  // проиграть на другом. Здесь не ждут события, а проверяют признак.
  //
  // Останавливается досрочно, если фокус ушёл на другой элемент: человек успел
  // нажать сам, и отбирать у него курсор обратно нельзя.
  function focusUntilCaret(el, opts) {
    if (!el) return Promise.resolve(false);
    focus(el, opts);
    if (caretIsLive(el)) return Promise.resolve(true);
    return new Promise((resolve) => {
      const started = Date.now();
      const timer = setInterval(() => {
        const doc = global.document;
        const active = doc && doc.activeElement;
        const stolen = active && active !== el && active !== doc.body;
        if (caretIsLive(el)) { clearInterval(timer); resolve(true); return; }
        if (stolen || (Date.now() - started) >= LAUNCH_HOLD_MS) {
          clearInterval(timer);
          resolve(false);
          return;
        }
        focus(el, opts);
      }, 120);
    });
  }

  // ── Enter ─────────────────────────────────────────────────────────────────
  //
  // На столе Enter отправляет, Shift+Enter переносит строку — так во всех чатах,
  // и переучивать никого не надо.
  //
  // На телефоне Shift держать нечем, а перенос строки нужен, поэтому синяя
  // клавиша переносит строку, а отправка остаётся за стрелкой в поле. Обратный
  // выбор («синяя отправляет») отнимает у человека абзацы совсем: другого
  // способа перенести строку на экранной клавиатуре нет.
  //
  // `isComposing` — не перестраховка. Пока идёт набор иероглифов или составной
  // буквы, Enter означает «подтвердить подсказку», и без этой проверки половина
  // недописанного слова улетает учителю. Второй признак, `keyCode === 229`, —
  // для старых движков, где `isComposing` не выставляется.
  function enterSends(e) {
    if (!e || e.key !== 'Enter') return false;
    if (e.isComposing || e.keyCode === 229) return false;
    if (e.shiftKey || e.altKey || e.ctrlKey || e.metaKey) return false;
    return !onScreenKeyboard();
  }

  // Что написать на синей клавише экранной клавиатуры. Подпись обязана
  // совпадать с делом: клавиша с надписью «отправить», которая переносит
  // строку, — это поломка, а не мелочь.
  function enterKeyHint() {
    return onScreenKeyboard() ? 'enter' : 'send';
  }

  global.LexComposerInput = Object.freeze({
    shellPlatform,
    onScreenKeyboard,
    focus,
    blur,
    caretIsLive,
    focusUntilCaret,
    launchHoldMs: LAUNCH_HOLD_MS,
    enterSends,
    enterKeyHint,
  });
})(typeof self !== 'undefined' ? self : globalThis);
