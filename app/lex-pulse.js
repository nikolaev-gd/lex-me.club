// lex-pulse.js — ОДИН таймер пульса для браузерных поверхностей (расширение и
// страница lex-me.club/app). Приложение на iPhone держит то же самое на Swift:
// ios/Lex/Lex/Pulse.swift, с тем же поведением.
//
// ── Что это ─────────────────────────────────────────────────────────────────
//
// Пульс — «клиент жив, шлём отметку с такой-то частотой». И больше ничего.
// Модуль отвечает ровно за три вещи:
//
//   • первый удар — сразу, в момент start(), а не через интервал: срок на
//     сервере взводится первым ударом, и дыра до него не должна быть длиннее
//     интервала;
//   • следующие удары — раз в `everyMs`;
//   • удар уходит сам по себе, и таймер его НЕ ЖДЁТ. Зависший запрос (пакеты
//     перестали ходить, сокет цел — так выглядит метро) не должен задерживать
//     следующие удары: человек, вернувшийся в сеть через две секунды, иначе
//     нашёл бы разговор закрытым. Упавший удар (исключение или отказавшее
//     обещание) пульс не останавливает — следующий уйдёт по расписанию.
//
// ── Чего здесь нет, и почему это граница, а не недоделка ───────────────────
//
// Частота, то, ЧТО несёт удар, КУДА и КАК он доставляется, что делать с
// ответом, когда пульс заводить и когда гасить — всё это решает тот, кто
// пульс заводит, и передаёт сюда параметрами (`everyMs`, `beat`). Пользуется
// модулем не только голосовой разговор: живая диктовка подключается к нему со
// своими правилами и своей доставкой. Стоит сюда просочиться хоть одному
// правилу голоса — номеру звонка, причине закрытия, отметке про речь учителя,
// — и диктовке подключиться станет не к чему. Поэтому в коде модуля нет ни
// одного слова про голос, звонок или сервер, и это стережёт
// dev-tools/test-pulse.mjs.
//
// Тот же принцип, что у серверного supabase/functions/_shared/voice-limits.ts:
// общий кусок владеет механикой, всё про окружение приходит параметрами.
//
// Файл грузится и веб-страницей, у которой требование — ноль `chrome.*` во
// всём графе зависимостей (dev-tools/check-webchat-clean.sh).
(function (global) {
  'use strict';

  if (global.LexPulse) return;

  // start({ everyMs, beat }) → { stop() }
  //
  //   everyMs — интервал между ударами, миллисекунды. Обязателен: своего числа
  //             у модуля нет. Не число, не конечное или не больше нуля —
  //             ошибка сразу, а не молча выбранное значение.
  //   beat    — функция одного удара. Её результат модулю не нужен; если она
  //             вернула обещание, его отказ гасится здесь, чтобы не всплыть
  //             необработанным.
  //
  // stop() гасит пульс; повторный вызов ничего не делает. Можно звать и
  // изнутри самого удара — после этого ни одного удара больше не будет.
  function start(opts) {
    const everyMs = opts && opts.everyMs;
    const beat = opts && opts.beat;
    if (typeof beat !== 'function') {
      throw new TypeError('LexPulse.start: beat must be a function');
    }
    if (typeof everyMs !== 'number' || !isFinite(everyMs) || everyMs <= 0) {
      throw new RangeError('LexPulse.start: everyMs must be a positive finite number, got ' + String(everyMs));
    }

    let timer = null;
    let stopped = false;

    const fire = () => {
      if (stopped) return;
      try {
        const result = beat();
        if (result && typeof result.then === 'function') result.then(null, () => {});
      } catch (_) { /* упавший удар пульс не гасит — следующий по расписанию */ }
    };

    fire();
    if (!stopped) timer = setInterval(fire, everyMs);

    return {
      stop() {
        stopped = true;
        if (timer !== null) { clearInterval(timer); timer = null; }
      },
    };
  }

  global.LexPulse = Object.freeze({ start });
})(typeof self !== 'undefined' ? self : globalThis);
