// lex-voice-events.js — ОДНО место, где записаны имена кадров транспорта
// голосовой сессии. Общее для расширения и веб-страницы: обе поверхности на
// JavaScript и грузят обычные глобальные модули.
//
// ── Зачем отдельный файл ────────────────────────────────────────────────────
//
// Имя `output_audio_buffer.started` — БЕЗ приставки `response.`. Приставку
// носят кадры ОТВЕТА, а эта пара — кадры транспорта WebRTC, и провайдер шлёт
// их именно так. Написанное с приставкой имя не даёт ни ошибки, ни
// предупреждения: условие просто не совпадает никогда, и ветка, которая должна
// была сработать, молча не срабатывает.
//
// Имя было выписано руками в ЧЕТЫРЁХ местах, и ошиблись в трёх сразу — это
// свойство копий, а не невнимательности. Три починили в v1.193.2 (расширение,
// серверный слушатель, айфон), четвёртая дожила до v1.193.4 в веб-версии, где
// её никто не искал, потому что тамошний сторож смотрел на список файлов,
// написанный руками, и веба в нём не было.
//
// Поэтому здесь не «ещё одна копия», а ЕДИНСТВЕННЫЙ литерал на весь
// JavaScript: расширение и веб берут имена отсюда, а собственный литерал в
// браузерном коде запрещён и валит `dev-tools/test-voice-event-names.mjs`.
//
// ── Кто сюда НЕ ходит, и почему это нормально ───────────────────────────────
//
// Две поверхности физически не могут взять этот файл: приложение на iPhone
// (Swift, `ios/Lex/Lex/VoiceSession.swift`) и серверные функции (Deno/TypeScript,
// `supabase/functions/`). У них остаются свои строки — но не «на честном
// слове»: тот же сторож читает значения ОТСЮДА и сверяет с тем, что написано
// там. Разъезд валит проверку с обеих сторон.
//
// Ничего, кроме констант, здесь быть не должно: файл грузится и веб-страницей,
// у которой требование — ноль `chrome.*` во всём графе зависимостей
// (`dev-tools/check-webchat-clean.sh`).
(function (global) {
  'use strict';

  if (global.LexVoiceEvents) return;

  global.LexVoiceEvents = Object.freeze({
    // Учитель заговорил: звук ответа пошёл в динамик.
    OUTPUT_AUDIO_STARTED: 'output_audio_buffer.started',
    // Учитель договорил: звук ответа кончился.
    OUTPUT_AUDIO_STOPPED: 'output_audio_buffer.stopped',
    // Недоигранный звук выброшен — приходит вместо `.stopped`, когда ответ
    // оборвали.
    OUTPUT_AUDIO_CLEARED: 'output_audio_buffer.cleared',
    // Это КОМАНДА в сторону провайдера, а не кадр от него: «выброси то, что
    // ещё не доиграно». Лежит рядом, потому что ошибиться в приставке здесь
    // ровно так же легко и так же тихо.
    OUTPUT_AUDIO_CLEAR: 'output_audio_buffer.clear',
  });
})(typeof self !== 'undefined' ? self : globalThis);
