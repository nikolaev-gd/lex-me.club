// lex-turn-id.js — номер операции и уиды реплик, которые из него считаются.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Строку реплики в public.video_chat_turns пишут
// двое: приложение своим пушем и сервер по ходу ответа. Сходятся они в ОДНУ
// строку только через уникальный индекс по (account_id, video_id, turn_uid),
// то есть только если обе стороны выдали один и тот же уид. Разойдись правило —
// на каждый пузырь придётся по две строки, и каждый ход будет виден в беседе
// дважды.
//
// Прецедент прямой и уже оплаченный: правило legacyUid живёт одновременно в
// video-threads.js и в бэкфилле chat_turns_uid_sync.sql, и шапка той миграции
// называет их совпадение условием безопасности — разойдись они, первая же
// синхронизация задвоила бы всю историю. Здесь то же самое делается ещё раз, и
// поэтому правило лежит в одном файле на обе браузерные поверхности, а не в
// двух похожих строчках в разных концах репозитория.
//
// Копий этого правила в проекте всё равно больше одной, и это не недосмотр:
// у айфона нет ни строчки общего кода с браузерными поверхностями (Swift), а
// у сервера — SQL. Три языка, три записи одного правила:
//
//   здесь                                    — расширение и веб-страница
//   ios/Lex/Lex/ChatStore.swift, opTurnIds   — айфон
//   supabase/migrations/chat_turns_server_rules.sql, lex_turn_begin — сервер
//
// Меняешь правило — меняешь все три, одной задачей.

(function (global) {
  'use strict';

  // Номер операции — метка ОДНОГО нажатия человека. Чеканится в момент
  // нажатия и НЕ перечеканивается при повторе отправки: перегенерация убила бы
  // всю схему — сервер опознаёт повтор именно по нему и на повторе не идёт к
  // модели второй раз. Та же формулировка стоит у голосового reportId в
  // background.js, и она там не для красоты.
  function newOpId() {
    if (typeof crypto !== 'undefined' && crypto.randomUUID) return crypto.randomUUID();
    return `op-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
  }

  // Уиды пары реплик. Никакого хеширования: turn_uid — колонка text, и
  // составные строковые уиды в ней уже живут (legacy:<ключ>:<номер>).
  function userTurnUid(opId) { return `${opId}:u`; }
  function assistantTurnUid(opId) { return `${opId}:a`; }

  // Время авторства пары. Метки ОБЯЗАНЫ различаться: порядок ленты везде —
  // authored_at по возрастанию, а при равной метке тайбрейк идёт по уиду. ':a'
  // меньше ':u', то есть на совпавшей миллисекунде ответ учителя встал бы ПЕРЕД
  // вопросом человека. Пока уиды были случайными, тайбрейк был просто лотереей
  // и в глаза не бросался; с предсказуемыми уидами он стал бы стабильно
  // неправильным. Разводим явно.
  function turnAuthoredAt(pressedAt) {
    const base = Number.isFinite(Number(pressedAt)) ? Number(pressedAt) : Date.now();
    return { userAt: base, assistantAt: base + 1 };
  }

  global.LexTurnId = { newOpId, userTurnUid, assistantTurnUid, turnAuthoredAt };
})(typeof self !== 'undefined' ? self : this);
